#!/usr/bin/env python3
"""Apply stable desktop identity and outbound network permissions to generated runners."""
from pathlib import Path
import plistlib
import re

ROOT = Path(__file__).resolve().parents[1] / 'apps/client'
mac = ROOT / 'macos/Runner'
if mac.is_dir() and (mac / 'Configs/AppInfo.xcconfig').exists():
    info = mac / 'Configs/AppInfo.xcconfig'
    text = info.read_text()
    for key, value in [('PRODUCT_NAME', 'Astracct'), ('PRODUCT_BUNDLE_IDENTIFIER', 'com.yuashie.astracct')]:
        text, count = re.subn(rf'^{key}\s*=.*$', f'{key} = {value}', text, flags=re.M)
        if count != 1:
            raise SystemExit(f'Expected one {key} in macOS runner')
    info.write_text(text)
    for name in ['DebugProfile.entitlements', 'Release.entitlements']:
        path = mac / name
        entitlements = plistlib.loads(path.read_bytes())
        entitlements['com.apple.security.network.client'] = True
        # Direct distribution: self-updates replace the writable application bundle.
        entitlements['com.apple.security.app-sandbox'] = False
        # The desktop vault uses the legacy Keychain: no shared access group or provisioning profile.
        path.write_bytes(plistlib.dumps(entitlements))
    # Flutter 3.47's macOS Impeller surface cache can crash on floating-window resize.
    # Keep the supported Skia fallback for this pinned SDK (docs.flutter.dev/perf/impeller).
    plist_path = mac / 'Info.plist'
    info_plist = plistlib.loads(plist_path.read_bytes())
    info_plist['FLTEnableImpeller'] = False
    plist_path.write_bytes(plistlib.dumps(info_plist))
    (mac / 'MainFlutterWindow.swift').write_text((ROOT.parents[1] / 'scripts/macos/MainFlutterWindow.swift').read_text())
    (mac / 'AppDelegate.swift').write_text((ROOT.parents[1] / 'scripts/macos/AppDelegate.swift').read_text())
    print('macOS identity and outbound network permission configured')

windows = ROOT / 'windows'
if (windows / 'CMakeLists.txt').exists():
    path = windows / 'CMakeLists.txt'
    text, count = re.subn(r'set\(BINARY_NAME "[^"]+"\)', 'set(BINARY_NAME "astracct")', path.read_text())
    if count != 1:
        raise SystemExit('Expected one Windows BINARY_NAME')
    # local_auth_windows 2.0.2 still uses the experimental WinRT coroutine ABI.
    # MSVC 14.51 rejects that header unless this documented compatibility opt-in
    # is set. Limit it to this plugin; remove when the upstream plugin migrates.
    # https://github.com/MicrosoftDocs/cpp-docs/blob/main/docs/porting/features-deprecated-in-visual-studio.md
    include = 'include(flutter/generated_plugins.cmake)'
    compatibility = """
# local_auth_windows experimental coroutine compatibility (MSVC 14.51+).
if(MSVC AND TARGET local_auth_windows_plugin)
  target_compile_definitions(local_auth_windows_plugin PRIVATE
    _SILENCE_EXPERIMENTAL_COROUTINE_DEPRECATION_WARNINGS)
endif()
"""
    if '_SILENCE_EXPERIMENTAL_COROUTINE_DEPRECATION_WARNINGS' not in text:
        if include not in text:
            raise SystemExit('Expected generated plugin include in Windows CMakeLists.txt')
        text = text.replace(include, include + compatibility)
    path.write_text(text)
    print('Windows executable: astracct.exe')

# Face ID disclosure for the native iOS target generated by CI.
ios_info = ROOT / 'ios/Runner/Info.plist'
if ios_info.exists():
    metadata = plistlib.loads(ios_info.read_bytes())
    metadata['NSFaceIDUsageDescription'] = '验证身份以解锁星账，保护本机账户信息。'
    ios_info.write_bytes(plistlib.dumps(metadata))
